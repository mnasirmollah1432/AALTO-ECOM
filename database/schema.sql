DROP TABLE IF EXISTS `order_items`;
DROP TABLE IF EXISTS `orders`;
DROP TABLE IF EXISTS `thanas`;
DROP TABLE IF EXISTS `districts`;
DROP TABLE IF EXISTS `delivery_zones`;
