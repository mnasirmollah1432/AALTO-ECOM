-- -------------------------------------------------------------
-- users: store administrators and customers
-- -------------------------------------------------------------
CREATE TABLE `users` (
    `id`             INT UNSIGNED     NOT NULL AUTO_INCREMENT,
    `name`           VARCHAR(120)     NOT NULL,
    `email`          VARCHAR(190)     NOT NULL,
    `phone`          VARCHAR(30)      NULL,
    `password_hash`  VARCHAR(255)     NOT NULL COMMENT 'password_hash() output - never plain text',
    `role`           ENUM('admin','customer') NOT NULL DEFAULT 'customer',
    `is_active`      TINYINT(1)       NOT NULL DEFAULT 1,
    `last_login_at`  DATETIME         NULL,
    `created_at`     TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`     TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_users_email` (`email`),
    KEY `idx_users_role_active` (`role`, `is_active`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- categories: optional one-level nesting via parent_id
-- -------------------------------------------------------------
CREATE TABLE `categories` (
    `id`           INT UNSIGNED     NOT NULL AUTO_INCREMENT,
    `parent_id`    INT UNSIGNED     NULL,
    `name`         VARCHAR(120)     NOT NULL,
    `slug`         VARCHAR(140)     NOT NULL,
    `description`  TEXT             NULL,
    `icon`         VARCHAR(60)      NULL COMMENT 'Bootstrap Icons class, e.g. bi-phone',
    `image_path`   VARCHAR(255)     NULL COMMENT 'relative to /public, e.g. uploads/categories/x.webp',
    `sort_order`   INT              NOT NULL DEFAULT 0,
    `is_active`    TINYINT(1)       NOT NULL DEFAULT 1,
    `created_at`   TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`   TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_categories_name` (`name`),
    UNIQUE KEY `uq_categories_slug` (`slug`),
    KEY `idx_categories_parent` (`parent_id`),
    KEY `idx_categories_active_sort` (`is_active`, `sort_order`),
    CONSTRAINT `fk_categories_parent`
        FOREIGN KEY (`parent_id`) REFERENCES `categories` (`id`)
        ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- products
-- -------------------------------------------------------------
CREATE TABLE `products` (
    `id`                 INT UNSIGNED     NOT NULL AUTO_INCREMENT,
    `category_id`        INT UNSIGNED     NOT NULL,
    `sku`                VARCHAR(64)      NOT NULL,
    `name`               VARCHAR(200)     NOT NULL,
    `slug`               VARCHAR(220)     NOT NULL,
    `short_description`  VARCHAR(500)     NULL,
    `description`        TEXT             NULL,
    `regular_price`      DECIMAL(12,2)    NOT NULL DEFAULT 0.00,
    `sale_price`         DECIMAL(12,2)    NULL COMMENT 'optional; ignored when NULL, 0 or not below regular_price',
    `price`              DECIMAL(12,2)
        AS (IF(`sale_price` IS NOT NULL AND `sale_price` > 0 AND `sale_price` < `regular_price`, `sale_price`, `regular_price`)) STORED
        COMMENT 'effective selling price - generated, never written directly',
    `cost_price`         DECIMAL(12,2)    NULL COMMENT 'internal, never shown to customers',
    `stock_quantity`     INT              NOT NULL DEFAULT 0 COMMENT 'with size/colour options: sum of product_variants',
    `has_sizes`          TINYINT(1)       NOT NULL DEFAULT 0 COMMENT 'size option on/off',
    `has_colours`        TINYINT(1)       NOT NULL DEFAULT 0 COMMENT 'colour option on/off',
    `weight_grams`       INT UNSIGNED     NULL,
    `is_featured`        TINYINT(1)       NOT NULL DEFAULT 0,
    `is_new`             TINYINT(1)       NOT NULL DEFAULT 0,
    `is_active`          TINYINT(1)       NOT NULL DEFAULT 1,
    `created_at`         TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`         TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_products_sku` (`sku`),
    UNIQUE KEY `uq_products_slug` (`slug`),
    KEY `idx_products_category_active` (`category_id`, `is_active`),
    KEY `idx_products_featured` (`is_active`, `is_featured`, `created_at`),
    KEY `idx_products_new` (`is_active`, `is_new`, `created_at`),
    KEY `idx_products_price` (`price`),
    FULLTEXT KEY `ft_products_search` (`name`, `short_description`, `description`),
    CONSTRAINT `fk_products_category`
        FOREIGN KEY (`category_id`) REFERENCES `categories` (`id`)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `chk_products_stock` CHECK (`stock_quantity` >= 0),
    CONSTRAINT `chk_products_regular_price` CHECK (`regular_price` >= 0),
    CONSTRAINT `chk_products_sale_price` CHECK (`sale_price` IS NULL OR `sale_price` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- product_images: several images per product, one primary
-- -------------------------------------------------------------
CREATE TABLE `product_images` (
    `id`          INT UNSIGNED     NOT NULL AUTO_INCREMENT,
    `product_id`  INT UNSIGNED     NOT NULL,
    `image_path`  VARCHAR(255)     NOT NULL COMMENT 'relative to /public, e.g. uploads/products/x.webp',
    `alt_text`    VARCHAR(200)     NULL,
    `sort_order`  INT              NOT NULL DEFAULT 0,
    `is_primary`  TINYINT(1)       NOT NULL DEFAULT 0,
    `created_at`  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    KEY `idx_product_images_product` (`product_id`, `is_primary`, `sort_order`),
    CONSTRAINT `fk_product_images_product`
        FOREIGN KEY (`product_id`) REFERENCES `products` (`id`)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- product_variants: size / colour options with their own stock.
-- One row per option combination; '' = option not used. When a
-- product uses options, products.stock_quantity is kept equal to
-- the sum of its variants (listings and badges read the product).
-- -------------------------------------------------------------
CREATE TABLE `product_variants` (
    `id`              INT UNSIGNED     NOT NULL AUTO_INCREMENT,
    `product_id`      INT UNSIGNED     NOT NULL,
    `size`            VARCHAR(40)      NOT NULL DEFAULT '' COMMENT 'empty when sizes are off',
    `colour`          VARCHAR(40)      NOT NULL DEFAULT '' COMMENT 'empty when colours are off',
    `colour_hex`      CHAR(7)          NULL COMMENT 'swatch colour, e.g. #c0392b',
    `stock_quantity`  INT              NOT NULL DEFAULT 0,
    `sort_order`      INT              NOT NULL DEFAULT 0,
    `created_at`      TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`      TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_product_variants` (`product_id`, `size`, `colour`),
    CONSTRAINT `fk_product_variants_product`
        FOREIGN KEY (`product_id`) REFERENCES `products` (`id`)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT `chk_product_variants_stock` CHECK (`stock_quantity` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- -------------------------------------------------------------
-- Delivery: zones with a charge (e.g. Inside Dhaka 70, Outside
-- Dhaka 130); every district belongs to one zone; thanas belong
-- to a district. All editable in Admin -> Delivery.
-- -------------------------------------------------------------
CREATE TABLE `delivery_zones` (
    `id`          INT UNSIGNED     NOT NULL AUTO_INCREMENT,
    `name`        VARCHAR(80)      NOT NULL,
    `charge`      DECIMAL(10,2)    NOT NULL DEFAULT 0.00,
    `sort_order`  INT              NOT NULL DEFAULT 0,
    `created_at`  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_delivery_zones_name` (`name`),
    CONSTRAINT `chk_delivery_zones_charge` CHECK (`charge` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `districts` (
    `id`          INT UNSIGNED     NOT NULL AUTO_INCREMENT,
    `name`        VARCHAR(80)      NOT NULL,
    `bn_name`     VARCHAR(80)      NULL,
    `zone_id`     INT UNSIGNED     NOT NULL,
    `sort_order`  INT              NOT NULL DEFAULT 0,
    `is_active`   TINYINT(1)       NOT NULL DEFAULT 1,
    `created_at`  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_districts_name` (`name`),
    KEY `idx_districts_zone` (`zone_id`),
    KEY `idx_districts_active_sort` (`is_active`, `sort_order`),
    CONSTRAINT `fk_districts_zone`
        FOREIGN KEY (`zone_id`) REFERENCES `delivery_zones` (`id`)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `thanas` (
    `id`           INT UNSIGNED     NOT NULL AUTO_INCREMENT,
    `district_id`  INT UNSIGNED     NOT NULL,
    `name`         VARCHAR(80)      NOT NULL,
    `bn_name`      VARCHAR(80)      NULL,
    `is_active`    TINYINT(1)       NOT NULL DEFAULT 1,
    `created_at`   TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`   TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_thanas_district_name` (`district_id`, `name`),
    CONSTRAINT `fk_thanas_district`
        FOREIGN KEY (`district_id`) REFERENCES `districts` (`id`)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- -------------------------------------------------------------
-- orders: guest checkout collects name, mobile and address only;
-- they are stored on the order itself (user_id stays NULL)
-- -------------------------------------------------------------
CREATE TABLE `orders` (
    `id`                 INT UNSIGNED     NOT NULL AUTO_INCREMENT,
    `order_number`       VARCHAR(32)      NOT NULL,
    `user_id`            INT UNSIGNED     NULL,
    `status`             ENUM('pending','confirmed','processing','shipped','delivered','cancelled')
                                          NOT NULL DEFAULT 'pending',
    `payment_status`     ENUM('unpaid','paid','failed','refunded') NOT NULL DEFAULT 'unpaid',
    `payment_method`     VARCHAR(40)      NOT NULL DEFAULT 'cod' COMMENT 'cod = cash on delivery',
    `customer_name`      VARCHAR(120)     NOT NULL,
    `customer_email`     VARCHAR(190)     NULL COMMENT 'not collected at checkout',
    `customer_phone`     VARCHAR(20)      NOT NULL COMMENT 'normalised, e.g. 01712345678',
    `shipping_address`   VARCHAR(500)     NOT NULL COMMENT 'house / road / area as typed',
    `district_id`        INT UNSIGNED     NULL,
    `thana_id`           INT UNSIGNED     NULL,
    `shipping_district`  VARCHAR(80)      NULL COMMENT 'name snapshot',
    `shipping_thana`     VARCHAR(80)      NULL COMMENT 'name snapshot',
    `delivery_zone`      VARCHAR(80)      NULL COMMENT 'zone name snapshot',
    `courier`                VARCHAR(30)   NULL COMMENT 'steadfast; "sending" while the request runs',
    `courier_consignment_id` VARCHAR(40)   NULL,
    `courier_tracking_code`  VARCHAR(60)   NULL,
    `courier_status`         VARCHAR(60)   NULL COMMENT 'last status from the courier, e.g. in_review, delivered',
    `courier_cod_amount`     DECIMAL(12,2) NULL COMMENT 'cash the courier collects',
    `courier_sent_at`        DATETIME      NULL,
    `courier_updated_at`     DATETIME      NULL,
    `shipping_city`      VARCHAR(100)     NULL,
    `shipping_postcode`  VARCHAR(20)      NULL,
    `shipping_country`   VARCHAR(100)     NOT NULL DEFAULT 'Bangladesh',
    `subtotal`           DECIMAL(12,2)    NOT NULL DEFAULT 0.00,
    `shipping_fee`       DECIMAL(12,2)    NOT NULL DEFAULT 0.00,
    `discount_total`     DECIMAL(12,2)    NOT NULL DEFAULT 0.00,
    `tax_total`          DECIMAL(12,2)    NOT NULL DEFAULT 0.00,
    `grand_total`        DECIMAL(12,2)    NOT NULL DEFAULT 0.00,
    `currency`           CHAR(3)          NOT NULL DEFAULT 'BDT',
    `notes`              TEXT             NULL,
    `placed_at`          DATETIME         NULL,
    `created_at`         TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`         TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_orders_number` (`order_number`),
    KEY `idx_orders_user` (`user_id`, `created_at`),
    KEY `idx_orders_status` (`status`, `created_at`),
    KEY `idx_orders_payment_status` (`payment_status`),
    KEY `idx_orders_email` (`customer_email`),
    KEY `idx_orders_phone` (`customer_phone`),
    KEY `idx_orders_placed` (`placed_at`),
    KEY `idx_orders_district` (`district_id`),
    KEY `idx_orders_thana` (`thana_id`),
    UNIQUE KEY `uq_orders_consignment` (`courier`, `courier_consignment_id`),
    KEY `idx_orders_courier_status` (`courier_status`),
    CONSTRAINT `fk_orders_district`
        FOREIGN KEY (`district_id`) REFERENCES `districts` (`id`)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `fk_orders_thana`
        FOREIGN KEY (`thana_id`) REFERENCES `thanas` (`id`)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `fk_orders_user`
        FOREIGN KEY (`user_id`) REFERENCES `users` (`id`)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `chk_orders_amounts`
        CHECK (`subtotal` >= 0 AND `shipping_fee` >= 0 AND `discount_total` >= 0 AND `tax_total` >= 0 AND `grand_total` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- order_items: product name/SKU/price are snapshots taken at
-- checkout; product_id is kept as a link but may become NULL
-- if the product is deleted later
-- -------------------------------------------------------------
CREATE TABLE `order_items` (
    `id`            INT UNSIGNED     NOT NULL AUTO_INCREMENT,
    `order_id`      INT UNSIGNED     NOT NULL,
    `product_id`    INT UNSIGNED     NULL,
    `variant_id`    INT UNSIGNED     NULL,
    `product_name`  VARCHAR(200)     NOT NULL,
    `product_sku`   VARCHAR(64)      NOT NULL,
    `variant_label` VARCHAR(120)     NULL COMMENT 'e.g. Size: M · Colour: Red',
    `unit_price`    DECIMAL(12,2)    NOT NULL,
    `quantity`      INT UNSIGNED     NOT NULL DEFAULT 1,
    `line_total`    DECIMAL(12,2)    NOT NULL,
    `created_at`    TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`    TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    KEY `idx_order_items_order` (`order_id`),
    KEY `idx_order_items_product` (`product_id`),
    KEY `idx_order_items_variant` (`variant_id`),
    CONSTRAINT `fk_order_items_order`
        FOREIGN KEY (`order_id`) REFERENCES `orders` (`id`)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT `fk_order_items_product`
        FOREIGN KEY (`product_id`) REFERENCES `products` (`id`)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `fk_order_items_variant`
        FOREIGN KEY (`variant_id`) REFERENCES `product_variants` (`id`)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `chk_order_items_values`
        CHECK (`quantity` > 0 AND `unit_price` >= 0 AND `line_total` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- login_attempts: failed admin logins, used for brute-force
-- lockout. Rows older than a day are purged automatically.
-- -------------------------------------------------------------
CREATE TABLE `login_attempts` (
    `id`            BIGINT UNSIGNED  NOT NULL AUTO_INCREMENT,
    `email`         VARCHAR(190)     NOT NULL,
    `ip_address`    VARCHAR(45)      NOT NULL,
    `attempted_at`  DATETIME         NOT NULL,
    PRIMARY KEY (`id`),
    KEY `idx_login_attempts_ip_time` (`ip_address`, `attempted_at`),
    KEY `idx_login_attempts_email_ip` (`email`, `ip_address`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- order_sequences: one counter per day for readable order numbers
-- (AM-20260924-00001). Incremented atomically inside the order
-- transaction, so numbers never repeat, even under load.
-- -------------------------------------------------------------
CREATE TABLE `order_sequences` (
    `seq_date`   DATE          NOT NULL,
    `seq_value`  INT UNSIGNED  NOT NULL,
    PRIMARY KEY (`seq_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- order_status_history: every status change (who, when, why).
-- from_status NULL = the order was placed; admin_id NULL = shopper.
-- -------------------------------------------------------------
CREATE TABLE `order_status_history` (
    `id`           INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    `order_id`     INT UNSIGNED  NOT NULL,
    `from_status`  VARCHAR(20)   NULL COMMENT 'NULL = order placed',
    `to_status`    VARCHAR(20)   NOT NULL,
    `note`         VARCHAR(500)  NULL,
    `admin_id`     INT UNSIGNED  NULL COMMENT 'NULL = customer / system',
    `created_at`   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    KEY `idx_order_status_history_order` (`order_id`, `created_at`),
    CONSTRAINT `fk_order_status_history_order`
        FOREIGN KEY (`order_id`) REFERENCES `orders` (`id`)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT `fk_order_status_history_admin`
        FOREIGN KEY (`admin_id`) REFERENCES `users` (`id`)
        ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -------------------------------------------------------------
-- settings: small key/value store for admin-editable options
